/* ============================================================
   timedGames — "이 게임의 기록은 흐른 시간인가"
   ------------------------------------------------------------
   서버가 게임에 대해 아는 **유일한 사실**이다. 규칙도 점수 계산도 모르고,
   오직 "신고된 숫자를 경과 시간과 견줘도 되는가" 하나만 안다.

   왜 필요한가: 자기신고 기록의 상한 검사는 "1초 만에 10분을 버텼다"를 막는 건데,
   그 산수가 성립하려면 신고값이 **시간**이어야 한다. 숫자 야구처럼 점수가 기록인
   게임에 같은 산수를 들이대면 두 가지가 동시에 일어난다.
     - 방어가 사라진다(점수는 시간과 무관하니 사실상 다 통과한다)
     - 그런데도 **게임 설계를 묶는다**(점수 규모를 키우면 없던 상한에 걸린다)
   실제로 baseball/config.ts가 "점수를 열 배로 올리면 서버 검사에 걸린다"고 적어 두고
   있었다. 서버가 모르는 채로 가정하면, 모르는 쪽이 아니라 **틀린 쪽으로** 넘어진다.

   ⚠️ 이 표는 **방어를 켜는 옵션**이지 게임 등록부가 아니다. 여기 없는 게임은 검사를
      건너뛸 뿐 아무것도 막히지 않는다 — 그래서 게임을 추가할 때 서버를 배포하지
      않아도 된다("서버는 게임을 모른다"가 이만큼은 지켜진다). 새로 만든 게임의 기록이
      생존 tick이고 그 방어를 켜고 싶을 때만 한 줄 넣는다.
   ⚠️ 게임플레이의 정본은 앱의 GameRegistry(`scoreUnit`)다. 여기는 그중 서버가 쓸 수
      있는 한 조각을 따로 적어 둔 것이고, 어긋나면 **방어가 약해질 뿐** 판정은 안 갈린다.
      약해지는 걸 사람이 알아챌 방법이 없어서, 어긋나면 tests/GameTables.test.ts가 깨진다.
   ============================================================ */

/** 기록이 생존 tick(60tick = 1초)인 게임들. 여기 없으면 시간으로 견주지 않는다. */
const TIMED_GAMES = new Set(["jungnim", "curve", "floor"]);

export function isTimedGame(gameId: string): boolean {
  return TIMED_GAMES.has(gameId);
}
