/* ============================================================
   IGame — 게임이 구현할 계약
   ------------------------------------------------------------
   core는 이 인터페이스만 알고, 구체 게임(JungnimGame 등)은 모른다.

   죽림고수 하나만 보고 만든 잠정 계약이었고, 둘째 게임(커브 피버)이 실제로
   붙으면서 검증됐다 — 넓힌 곳은 선택 메서드뿐이고 필수 계약은 그대로였다.
   관전 데이터는 위치 하나로 충분했고(꼬리 이력은 받는 쪽이 쌓는다), 입력도
   4방향의 부분집합으로 족했다. (DESIGN.md 3절 "잠정적으로 열어둘 지점" 참조)

   이후 `consumeSounds`가 하나 늘었다. 두 게임이 **이미 만들어 놓은 사건**(아이템
   획득·니어 미스 스침)에 소리를 붙이려니 그것을 밖으로 낼 통로가 없어서다 —
   상상이 아니라 실제 요구였고, 옵셔널이라 안 쓰는 게임은 그대로다.

   네 번째 게임(숫자 야구)이 `typeKey`를 하나 더 요구했다. 앞의 셋은 전부 4방향
   회피라 InputState로 충분했는데, 이 게임은 **숫자를 친다**. 방향 넷으로 자릿수를
   돌려 고르게 만들 수도 있었지만 그건 속도가 곧 점수인 게임을 망친다.
   ⚠️ InputState를 숫자로 넓히지 **않은** 이유: 저건 「누르고 있다」의 스냅샷이고
   타자는 「누른 순간」의 연속이다. 60Hz로 뽑아 보면 스텝 사이에 눌렸다 떼인 키가
   통째로 사라진다 — 회피 게임에서는 1/60초의 누락이 무해하지만 타자에서는 글자가
   빠지는 버그다. 그래서 눌린 사건을 그때그때 밀어 넣는 통로를 따로 열었다.

   같은 게임이 두 가지를 더 드러냈다.
   - `getPosition`은 "위치"가 아니라 **관전 중계용 숫자 둘**이었다. 앞의 셋이 전부
     판 위를 움직이는 게임이라 좌표라고 적어 뒀을 뿐이고, 판이 없는 게임이 나오자
     계약이 실제보다 좁게 적혀 있었음이 드러났다. 처음에는 뜻만 넓히고 이름은 뒀는데,
     그러면 `{x, y}`라는 필드 이름이 계속 "좌표다"라고 말한다 — 결국 `{a, b}`로
     바꿨다(SpectateSignal). 메서드 이름은 남겼다: 부르는 쪽 넷 중 셋에게는 여전히
     위치를 묻는 일이고, 뜻은 반환 타입이 이미 말하고 있다.
   - `syncPeers`를 선택으로 내렸다. 남의 시각 요소를 쌓을 게 없는 게임이 실제로
     나왔고, 필수인 채로 두면 빈 몸 메서드를 강요한다(바로 아래 규칙의 위반이다).

   ⚠️ 선택 메서드는 여기까지다. 다섯 번째 게임이 실제로 요구하기 전에는 넓히지
   않는다 — 상상으로 넓힌 계약은 빈 구현을 강요한다. */

import type { InputState, SpectateSignal, SpectateTarget, PeerState, SpawnContext } from "./types";
import type { IRenderer } from "./IRenderer";

export interface IGame {
  /** 시드로 결정론 초기화. 여기서 SeededRNG 인스턴스를 만든다.
   *  self는 멀티에서 이 클라의 신원(순번·인원) — 플레이어별로 스폰을 나눠 갖는 게임만
   *  쓴다. 스폰이 고정인 게임은 매개변수를 아예 안 받아 무시하면 된다(TS는 매개변수를
   *  덜 받는 구현을 허용한다 — 죽림고수의 init(seed)가 그대로 이 계약을 만족한다). */
  init(seed: number, self?: SpawnContext): void;

  /** 고정 스텝(1/60초)마다 호출. 실측 deltaTime을 받지 않는다 — 결정론 불변식.
   *  ⚠️ 공통 월드(모두가 공유하는 시드 기반 부분)는 로컬 플레이어가 죽어도 계속
   *  전진해야 한다 — 관전자가 살아있는 남의 화면을 그리려면 월드가 살아있어야 함. */
  update(tick: number, input: InputState): void;

  /** 자기 자신을 렌더. alpha는 프레임 간 보간용(로직엔 영향 없음). */
  render(r: IRenderer, alpha: number): void;

  /** 관전 렌더: 공통 월드 + 대상(남)의 위치를 그린다. 자기 플레이어는 안 그린다. */
  renderSpectator(r: IRenderer, target: SpectateTarget): void;

  /** 로컬 사망 판정. 각 클라이언트가 자기 화면에서 판단한다. */
  isPlayerDead(): boolean;

  /** 관전 중계에 실을 숫자 둘(a·b). **대개 자기 위치(게임 좌표계)지만 뜻은 게임이 정한다** —
   *  통로가 숫자 두 개일 뿐이고, core도 서버도 그 뜻을 모른 채 나른다(SpectateSignal 참조).
   *  숫자 야구처럼 판 위의 위치라는 게 없는 게임은 진척도를 싣는다.
   *  ⚠️ 무엇을 싣든 renderSpectator가 **같은 뜻으로** 읽어야 한다. 둘은 한 쌍이다. */
  getPosition(): SpectateSignal;

  /** (선택) 관전 대상(남)들의 현재 신호를 게임에 알린다. 게임은 이 정보로 각자의
   *  로컬 전용 시각 요소를 근사해 renderSpectator에서 그린다(커브 피버의 남의 꼬리).
   *  ⚠️ 쌓을 게 없는 게임은 **구현하지 않는다.** 필수로 두면 그런 게임이 빈 몸의
   *  메서드를 하나 갖게 되는데, 빈 구현은 "이 게임엔 없다"가 아니라 "아직 안 썼다"로
   *  읽혀 다음 사람이 지워도 되는지 알 수 없다. */
  syncPeers?(peers: readonly PeerState[]): void;

  /** 순위 기준값. 죽림고수는 생존시간(tick). scoreDirection과 함께 해석된다. */
  getScore(): number;

  /** (선택) 게임 고유의 게이지 값(0~1) — 캔버스 밖 DOM HUD에 바로 표시된다.
   *  커브 피버의 「스릴 게이지」가 이걸 구현한다. 게이지가 없는 게임은 구현 안 하면
   *  된다(그러면 HUD가 게이지 줄을 숨긴다). */
  getGauge?(): number;

  /** (선택) 이번 스텝에 상대에게 쏠 방해 발사가 있으면 걸 수 있는 **디버프 풀**을 돌려주고
   *  소비한다. 러너가 매 스텝 폴링한다. 이 중 하나를 뽑아(랜덤) 누구에게 보낼지는 앱이 정한다
   *  — 게임 update와 core·서버는 슬러그를 모른다. 없으면 null. */
  consumePendingFire?(): readonly { kind: string; durationMs: number }[] | null;

  /** (선택) 이번 스텝에 **남들 화면에도 보여야 할** 시각 이벤트가 생겼으면 그 슬러그를
   *  돌려주고 소비한다(없으면 null). 앱이 위치 전송에 얹어 보내고, 서버는 의미를 모른 채
   *  다음 스냅샷에 한 번 실어 중계한다.
   *  ⚠️ 판정이 아니라 **연출 동기화 전용**이다. 이게 유실돼도 게임 진행은 갈리지 않는다
   *  — 로컬에서만 일어난 일(예: 내가 지운 화살)을 남의 관전 화면에서 흉내 내기 위한 것. */
  consumePeerEvent?(): string | null;

  /** (선택) 남이 낸 시각 이벤트가 도착했다. 그 사람을 관전 중일 때 같은 연출을 재현한다.
   *  모르는 kind는 무시한다. */
  applyPeerEvent?(id: string, kind: string): void;

  /** (선택) 이번 스텝에 난 **소리**의 슬러그를 돌려주고 소비한다(없으면 null).
   *  러너가 프레임 단위로 모아 앱에 넘기고, 앱이 슬러그를 실제 소리에 대응시킨다
   *  — core도 서버도 슬러그의 뜻을 모른다(consumePendingFire와 같은 결).
   *  ⚠️ 판정이 아니라 출력이다. 여기서 무엇을 내든 tick·시드·결과는 갈리지 않는다.
   *  ⚠️ 관전 중(로컬 사망 후)에는 내지 않는다 — 공통 월드는 계속 돌지만 그건 남의 판이다. */
  consumeSounds?(): readonly string[] | null;

  /** (선택) 글자 하나가 눌렸다. 방향 넷으로는 표현되지 않는 입력을 쓰는 게임용이다.
   *  슬러그는 `"0"`~`"9"` · `"back"`(한 글자 지우기) · `"enter"`(제출) —
   *  core도 앱도 뜻을 모르고 그대로 넘긴다(consumeSounds와 같은 결).
   *  ⚠️ 고정 스텝 밖에서 온다. 로컬 입력이라 결정론과 무관하고(InputManager 주석),
   *  이 게임의 진행은 tick이 아니라 사람이 친 순서로만 움직인다. */
  typeKey?(key: string): void;

  /** (선택) 남의 발사에 맞았을 때 호출. 게임이 아는 kind면 자기 로컬 상태에만 효과를
   *  적용한다(예: 좌우 조작 반전·회전 둔화). 결정론 안전 — 공통 월드가 아니라 그 클라의
   *  입력/시야만 바뀐다. 시각계·모르는 kind는 무시한다(화면 연출은 앱이 처리). */
  applyEffect?(kind: string, durationMs: number): void;
}
